const preserveWhitespace = (original: string, translated: string) => {
  const leading = original.match(/^\s*/)?.[0] ?? "";
  const trailing = original.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
};

export const translateText = (value: string, language: Language) => {
  if (language === "nl") return value;

  const trimmed = value.trim();
  if (!trimmed) return value;

  const exact = exactTranslations[trimmed];
  if (exact) return preserveWhitespace(value, exact);

  let translated = trimmed;
  for (const [pattern, replacement] of phraseTranslations) {
    translated = translated.replace(pattern, replacement);
  }

  return translated === trimmed ? value : preserveWhitespace(value, translated);
};
