-- ============================================================================
-- Endurance — telemetrie-archief per auto en baan
-- Datum: 2026-10-25
--
-- Punt 7 van "Na de race — 24 oktober 2026". Het ingest-pad bewaart per ronde
-- één rij in endurance_strategy_lap_samples, maar die rijen hangen aan een
-- race_run en zijn na de race nergens meer te gebruiken: er is geen plek waar
-- een afgeronde race blijft staan als leerbron voor tankduur en stintlengte
-- (punt 8). Dit bestand maakt die plek.
--
-- Drie onderdelen:
--
--   1. endurance_telemetry_archive — één rij per gereden ronde, met auto, baan,
--      configuratie, rondetijd, verbruik en slijtage per wiel.
--   2. endurance_archive_run_identity() — de auto en baan van een run, bepaald
--      uit het EERSTE bewijs dat die run zelf heeft vastgelegd. De waarde wordt
--      daarna nooit meer bijgewerkt, dus een autowissel later in de race
--      herschrijft het verleden niet.
--   3. endurance_archive_tick() — de uurlijkse taak die samples van afgeronde
--      events overzet. Idempotent (ON CONFLICT DO NOTHING), dus de eerste loop
--      vult ook terug wat er al staat: de race van 24-10 heeft 284 samples.
--
-- Bewust buiten het ingest-pad: een archiefrij is afgeleide data. De ingest mag
-- niet trager of breekbaarder worden van een tweede schrijfactie, en een fout
-- in het archief mag nooit een ronde laten verdwijnen uit de pitwall.
--
-- Bewust geen foreign keys: het archief moet een event, team of run overleven.
-- Met een FK zou het opruimen van een event (en daarmee zijn runs) de
-- geschiedenis meenemen — precies wat dit archief moet voorkomen.
--
-- Coureur en weer staan er niet in. De coureur hoort bij de koppeling op de
-- rijder (punt 5) en weer wordt door de plugin niet gemeten; een kolom die
-- altijd leeg is suggereert een meting die er niet is.
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. De archieftabel
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.endurance_telemetry_archive (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id             uuid NOT NULL,
  team_id              uuid NOT NULL,
  race_run_id          uuid NOT NULL,
  car_id               text,
  car_name             text,
  track_id             text,
  track_config         text,
  lap                  integer NOT NULL,
  -- Ruim bemeten. Een onmogelijke uitschieter hoort in het archief te staan en
  -- niet de hele taak te laten klappen op een numeric-overflow.
  lap_time_seconds     numeric(12,3),
  fuel_litres          numeric(9,3),
  fuel_per_lap_litres  numeric(8,3),
  wear_fl              numeric(6,2),
  wear_fr              numeric(6,2),
  wear_rl              numeric(6,2),
  wear_rr              numeric(6,2),
  captured_at          timestamptz NOT NULL,
  archived_at          timestamptz NOT NULL DEFAULT now(),

  -- De natuurlijke sleutel. Een run telt zijn eigen rondes; zonder race_run_id
  -- zou een herstart van dezelfde auto in hetzelfde event zijn rondes 1..n
  -- wegschrijven als duplicaat van de eerste run.
  CONSTRAINT endurance_telemetry_archive_run_lap_key UNIQUE (race_run_id, lap),

  -- Geen checks op de meetwaarden zelf. Een uitschieter (pitronde, uitloop)
  -- hoort in het archief te staan; de leerlaag van punt 8 filtert hem. Een
  -- CHECK die hier klapt zou de hele taak laten mislukken.
  CONSTRAINT endurance_telemetry_archive_lap_check CHECK (lap > 0)
);

CREATE INDEX IF NOT EXISTS endurance_telemetry_archive_event_team_idx
  ON public.endurance_telemetry_archive (event_id, team_id);

-- De leesvraag van punt 8: wat verbruikt deze auto op deze baan.
CREATE INDEX IF NOT EXISTS endurance_telemetry_archive_car_track_idx
  ON public.endurance_telemetry_archive (car_id, track_id);

CREATE INDEX IF NOT EXISTS endurance_telemetry_archive_team_captured_idx
  ON public.endurance_telemetry_archive (team_id, captured_at DESC);

COMMENT ON TABLE public.endurance_telemetry_archive IS
  'Archief per gereden ronde voor afgeronde endurance-events. Gevuld door endurance_archive_tick(), nooit door het ingest-pad.';
COMMENT ON COLUMN public.endurance_telemetry_archive.car_id IS
  'Auto zoals vastgelegd bij de start van de run. Een latere autowissel wijzigt bestaande rijen niet.';
COMMENT ON COLUMN public.endurance_telemetry_archive.track_id IS
  'iRacing track-id als tekst, zodat een plugin die geen numerieke id stuurt de taak niet laat klappen.';
COMMENT ON COLUMN public.endurance_telemetry_archive.fuel_litres IS
  'Brandstof aan het einde van de ronde, in liters.';
COMMENT ON COLUMN public.endurance_telemetry_archive.fuel_per_lap_litres IS
  'Verbruik van deze ronde. NULL wanneer de plausibiliteitstoets de meting afkeurde; de rondetijd blijft dan staan.';
COMMENT ON COLUMN public.endurance_telemetry_archive.wear_fl IS
  'Bandenslijtage als het percentage dat de plugin meet (100 = nieuw). NULL als uitgebreide telemetrie uit stond.';

-- ---------------------------------------------------------------------------
-- 2. RLS — lezen voor staff en eigen team, schrijven alleen via de taak
-- ---------------------------------------------------------------------------
ALTER TABLE public.endurance_telemetry_archive ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS endurance_telemetry_archive_staff_read ON public.endurance_telemetry_archive;
CREATE POLICY endurance_telemetry_archive_staff_read ON public.endurance_telemetry_archive
  FOR SELECT TO authenticated
  USING (public.is_endurance_staff(auth.uid()));

DROP POLICY IF EXISTS endurance_telemetry_archive_team_read ON public.endurance_telemetry_archive;
CREATE POLICY endurance_telemetry_archive_team_read ON public.endurance_telemetry_archive
  FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.endurance_team_members m
     WHERE m.team_id = endurance_telemetry_archive.team_id
       AND m.user_id = auth.uid()
  ));

-- Er is geen schrijfpolicy: het archief is afgeleide data en gaat alleen via
-- endurance_archive_tick() (SECURITY DEFINER) naar binnen. Een handmatige
-- schrijver zou de enige bron van waarheid naast het ingest-pad zetten.
--
-- Anon leest niets. Een publieke archiefpagina (punt 26) krijgt later een eigen
-- policy of een RPC; tot die tijd is een oud teamlid zonder lidmaatschap de
-- enige die zijn eigen rijen niet ziet, en dat is de veilige kant van de fout.
GRANT SELECT ON public.endurance_telemetry_archive TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.endurance_telemetry_archive TO service_role;
REVOKE INSERT, UPDATE, DELETE ON public.endurance_telemetry_archive FROM anon, authenticated;

-- ---------------------------------------------------------------------------
-- 3. Identiteit van een run: auto en baan, vastgelegd bij de start
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.endurance_archive_run_identity(p_race_run_id uuid)
RETURNS TABLE (car_id text, car_name text, track_id text, track_config text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'public', 'pg_temp'
AS $function$
  WITH eerste_auto AS (
    -- Het vroegste lap-event met een carId. Dat is de auto die er bij de start
    -- van de run in stond; een latere wissel komt pas in latere events.
    SELECT nullif(btrim(coalesce(e.payload #>> '{identity,carId}', '')), '')   AS car_id,
           nullif(btrim(coalesce(e.payload #>> '{identity,carName}', '')), '') AS car_name
      FROM public.endurance_telemetry_events e
     WHERE e.race_run_id = p_race_run_id
       AND nullif(btrim(coalesce(e.payload #>> '{identity,carId}', '')), '') IS NOT NULL
     ORDER BY e.captured_at, e.sequence
     LIMIT 1
  ),
  eerste_baan AS (
    SELECT nullif(btrim(coalesce(e.payload #>> '{identity,trackId}', '')), '')     AS track_id,
           nullif(btrim(coalesce(e.payload #>> '{identity,trackConfig}', '')), '') AS track_config
      FROM public.endurance_telemetry_events e
     WHERE e.race_run_id = p_race_run_id
       AND (nullif(btrim(coalesce(e.payload #>> '{identity,trackId}', '')), '') IS NOT NULL
            OR nullif(btrim(coalesce(e.payload #>> '{identity,trackConfig}', '')), '') IS NOT NULL)
     ORDER BY e.captured_at, e.sequence
     LIMIT 1
  ),
  laatste_snapshot AS (
    -- Terugvalpad voor een run zonder lap-events. De snapshot is de stand van
    -- nu, niet van de start; daarom staat hij achter de events, niet ervoor.
    SELECT l.car_id,
           l.track_config,
           l.v3_normalized
      FROM public.simhub_telemetry_latest l
     WHERE l.race_run_id = p_race_run_id
     ORDER BY l.received_at DESC
     LIMIT 1
  ),
  catalogus AS (
    SELECT cat.track_id::text AS track_id
      FROM public.endurance_race_runs r
      JOIN public.endurance_events ev ON ev.id = r.event_id
      JOIN public.endurance_iracing_events cat ON cat.id = ev.iracing_catalog_event_id
     WHERE r.id = p_race_run_id
  )
  SELECT coalesce(a.car_id,
                  nullif(btrim(snap.car_id), ''),
                  nullif(btrim(snap.v3_normalized #>> '{identity,carId}'), '')),
         coalesce(a.car_name,
                  nullif(btrim(snap.v3_normalized #>> '{identity,carName}'), '')),
         coalesce(b.track_id,
                  cat.track_id,
                  nullif(btrim(snap.v3_normalized #>> '{identity,trackId}'), '')),
         coalesce(b.track_config,
                  nullif(btrim(snap.track_config), ''),
                  nullif(btrim(snap.v3_normalized #>> '{identity,trackConfig}'), ''))
    FROM (SELECT 1) AS anker
    LEFT JOIN eerste_auto     a    ON true
    LEFT JOIN eerste_baan     b    ON true
    LEFT JOIN laatste_snapshot snap ON true
    LEFT JOIN catalogus       cat  ON true;
$function$;

COMMENT ON FUNCTION public.endurance_archive_run_identity(uuid) IS
  'Auto, autonaam, baan en configuratie van één race_run, uit het vroegste eigen bewijs. Alleen-lezen hulpfunctie voor het archief.';

-- ---------------------------------------------------------------------------
-- 4. De uurlijkse taak
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.endurance_archive_tick()
RETURNS TABLE (verwerkte_runs integer, gearchiveerde_rondes integer)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'public', 'pg_temp'
AS $function$
DECLARE
  v_runs   integer := 0;
  v_rondes integer := 0;
BEGIN
  -- Alleen afgeronde events. Een lopende race wordt pas gearchiveerd als de
  -- levensloop (endurance_tick_events) hem op completed heeft gezet; tot die
  -- tijd blijven de samples in het ingest-pad staan en is er niets verloren.
  --
  -- ON CONFLICT DO NOTHING maakt de taak herhaalbaar: wat al in het archief
  -- staat wordt overgeslagen, wat na de eerste loop nog binnenkomt wordt de
  -- volgende keer meegenomen.
  WITH runs AS (
    SELECT r.id, r.event_id, r.team_id, r.ended_at, r.started_at
      FROM public.endurance_race_runs r
      JOIN public.endurance_events e ON e.id = r.event_id
     WHERE e.status = 'completed'
       -- Alleen races. Practice heeft zijn eigen tabel (endurance_practice_laps)
       -- en zou het leren van tankduur per auto en baan vervuilen.
       AND r.run_kind = 'race'
  ),
  identiteit AS (
    SELECT runs.id AS run_id,
           i.car_id, i.car_name, i.track_id, i.track_config
      FROM runs
      CROSS JOIN LATERAL public.endurance_archive_run_identity(runs.id) AS i
  ),
  ingevoegd AS (
    INSERT INTO public.endurance_telemetry_archive (
      event_id, team_id, race_run_id,
      car_id, car_name, track_id, track_config,
      lap, lap_time_seconds, fuel_litres, fuel_per_lap_litres,
      wear_fl, wear_fr, wear_rl, wear_rr, captured_at
    )
    SELECT coalesce(s.event_id, r.event_id),
           coalesce(s.team_id, r.team_id),
           s.race_run_id,
           i.car_id, i.car_name, i.track_id, i.track_config,
           s.completed_laps,
           s.lap_time_seconds,
           s.fuel_end_litres,
           -- Alleen het verbruik van een goedgekeurde meting. Een afgekeurde
           -- meting levert geen getal op, maar de ronde zelf blijft bewaard.
           CASE WHEN s.valid_fuel_sample THEN s.fuel_used_litres END,
           s.wear_fl, s.wear_fr, s.wear_rl, s.wear_rr,
           coalesce(s.captured_at, r.ended_at, r.started_at, now())
      FROM public.endurance_strategy_lap_samples s
      JOIN runs r        ON r.id = s.race_run_id
      -- LEFT: een run zonder bruikbare identiteit levert een rij met een lege
      -- auto, nooit een verdwenen ronde.
      LEFT JOIN identiteit i ON i.run_id = s.race_run_id
     WHERE s.completed_laps IS NOT NULL
       AND s.completed_laps > 0
    ON CONFLICT (race_run_id, lap) DO NOTHING
    RETURNING race_run_id
  )
  SELECT count(*)::integer,
         count(DISTINCT race_run_id)::integer
    INTO v_rondes, v_runs
    FROM ingevoegd;

  RETURN QUERY SELECT v_runs, v_rondes;
END;
$function$;

COMMENT ON FUNCTION public.endurance_archive_tick() IS
  'Zet de lap-samples van afgeronde events over naar endurance_telemetry_archive. Idempotent; de eerste loop vult ook het verleden terug.';

-- De taak hoort bij de klok, niet bij een gebruiker: cron draait als eigenaar.
-- De hulpfunctie is alleen nodig binnen de taak.
REVOKE ALL ON FUNCTION public.endurance_archive_tick() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.endurance_archive_run_identity(uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.endurance_archive_tick() TO service_role;
GRANT EXECUTE ON FUNCTION public.endurance_archive_run_identity(uuid) TO service_role;

-- Elk uur, op minuut 17: na de levenslooptaak van elke 5 minuten, zodat een
-- event dat net op completed is gezet meteen dezelfde cyclus nog meegaat.
SELECT cron.unschedule('endurance-archive')
 WHERE EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'endurance-archive');

SELECT cron.schedule('endurance-archive', '17 * * * *', $cron$SELECT public.endurance_archive_tick()$cron$);

COMMIT;
